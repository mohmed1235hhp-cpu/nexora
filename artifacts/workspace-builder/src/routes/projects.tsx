import { createFileRoute, Link } from "@tanstack/react-router";
import { useEffect, useState } from "react";
import { AppShell, useLang } from "@/components/workspace/AppShell";
import { deleteProject, duplicateProject, listProjects, type StoredProject } from "@/lib/workspace/projects-store";
import { Copy, Trash2, ArrowRight } from "lucide-react";

export const Route = createFileRoute("/projects")({
  head: () => ({
    meta: [
      { title: "Projects — Cyber AI Workspace" },
      { name: "description", content: "Your projects, generated by your AI team." },
    ],
  }),
  component: ProjectsPage,
});

function ProjectsPage() {
  const { lang } = useLang();
  const ar = lang === "ar";
  const [projects, setProjects] = useState<StoredProject[]>([]);

  useEffect(() => {
    const refresh = () => setProjects(listProjects());
    refresh();
    window.addEventListener("cyberai:projects-changed", refresh);
    window.addEventListener("storage", refresh);
    return () => {
      window.removeEventListener("cyberai:projects-changed", refresh);
      window.removeEventListener("storage", refresh);
    };
  }, []);

  return (
    <AppShell>
      <div dir={ar ? "rtl" : "ltr"}>
        <div className="flex items-baseline justify-between mb-6">
          <h1 className="text-2xl sm:text-3xl font-semibold tracking-tight">
            {ar ? "مشاريعي" : "Projects"}
          </h1>
          <span className="text-sm text-muted-foreground">{projects.length}</span>
        </div>

        {projects.length === 0 ? (
          <div className="rounded-3xl border border-dashed border-border/60 bg-card/40 p-12 text-center">
            <div className="text-lg font-medium mb-2">{ar ? "لا توجد مشاريع بعد" : "No projects yet"}</div>
            <p className="text-sm text-muted-foreground mb-6">
              {ar ? "ابدأ من الصفحة الرئيسية وسنبني مشروعك." : "Start on the home page and we'll build your first project."}
            </p>
            <Link to="/" className="inline-flex items-center gap-2 rounded-full bg-primary text-primary-foreground px-4 py-2 text-sm">
              {ar ? "ابدأ الآن" : "Start now"} <ArrowRight className="h-4 w-4" />
            </Link>
          </div>
        ) : (
          <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
            {projects.map((p) => (
              <ProjectCard
                key={p.id}
                project={p}
                ar={ar}
                onDelete={() => {
                  deleteProject(p.id);
                  setProjects(listProjects());
                }}
                onDuplicate={() => {
                  duplicateProject(p.id);
                  setProjects(listProjects());
                }}
              />
            ))}
          </div>
        )}
      </div>
    </AppShell>
  );
}

function ProjectCard({
  project,
  onDelete,
  onDuplicate,
  ar,
}: {
  project: StoredProject;
  onDelete: () => void;
  onDuplicate: () => void;
  ar: boolean;
}) {
  const gradient = gradientFor(project.kind);
  return (
    <div className="group rounded-2xl border border-border/60 bg-card/60 backdrop-blur overflow-hidden hover:-translate-y-1 hover:shadow-2xl transition-all">
      <div className={`h-32 relative ${gradient}`}>
        <div className="absolute inset-0 bg-black/10" />
        <div className="absolute bottom-2 left-3 right-3 flex items-center justify-between text-white text-xs">
          <span className="rounded-full bg-black/30 backdrop-blur px-2 py-0.5 capitalize">{project.kind}</span>
          <span className="rounded-full bg-black/30 backdrop-blur px-2 py-0.5">v{project.version}</span>
        </div>
      </div>
      <div className="p-4">
        <div className="text-sm font-medium line-clamp-1">{project.name}</div>
        <div className="text-xs text-muted-foreground mt-1">
          {new Date(project.updatedAt).toLocaleDateString(ar ? "ar" : undefined)} · {statusLabel(project.status, ar)}
        </div>
        <div className="mt-3 h-1.5 rounded-full bg-muted overflow-hidden">
          <div className="h-full bg-primary transition-all" style={{ width: `${project.progress}%` }} />
        </div>
        <div className="mt-3 flex items-center gap-1">
          <Link
            to="/project/$id"
            params={{ id: project.id }}
            className="flex-1 rounded-lg bg-secondary text-secondary-foreground text-xs px-3 py-2 hover:bg-secondary/80 text-center transition"
          >
            {ar ? "متابعة" : "Continue"}
          </Link>
          <button onClick={onDuplicate} aria-label="Duplicate" className="h-8 w-8 grid place-items-center rounded-lg hover:bg-secondary transition">
            <Copy className="h-3.5 w-3.5" />
          </button>
          <button onClick={onDelete} aria-label="Delete" className="h-8 w-8 grid place-items-center rounded-lg hover:bg-destructive/15 text-muted-foreground hover:text-destructive transition">
            <Trash2 className="h-3.5 w-3.5" />
          </button>
        </div>
      </div>
    </div>
  );
}

function gradientFor(kind: string): string {
  switch (kind) {
    case "website": return "bg-gradient-to-br from-blue-500 via-indigo-500 to-purple-600";
    case "app": return "bg-gradient-to-br from-emerald-500 via-teal-500 to-cyan-600";
    case "image": return "bg-gradient-to-br from-pink-500 via-rose-500 to-orange-500";
    case "voice": return "bg-gradient-to-br from-violet-500 via-fuchsia-500 to-pink-500";
    case "content": return "bg-gradient-to-br from-amber-500 via-orange-500 to-red-500";
    case "code": return "bg-gradient-to-br from-slate-600 via-slate-700 to-slate-900";
    case "search": return "bg-gradient-to-br from-sky-500 via-blue-500 to-indigo-500";
    default: return "bg-gradient-to-br from-primary to-chart-4";
  }
}

function statusLabel(s: string, ar: boolean): string {
  if (s === "completed") return ar ? "مكتمل" : "Completed";
  if (s === "in_progress") return ar ? "قيد التنفيذ" : "In progress";
  return ar ? "يحتاج مراجعة" : "Needs review";
}
