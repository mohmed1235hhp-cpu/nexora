import type { AIRouter } from "../router/AIRouter";
import { TaskType } from "../types/task.types";
import { TextChatHandler } from "./TextChatHandler";
import { VoiceChatHandler } from "./VoiceChatHandler";
import { ImageGenerationHandler } from "./ImageGenerationHandler";
import { ImageAnalysisHandler } from "./ImageAnalysisHandler";
import { WebsiteGenerationHandler } from "./WebsiteGenerationHandler";
import { ApplicationGenerationHandler } from "./ApplicationGenerationHandler";
import { CodeReviewHandler } from "./CodeReviewHandler";
import { BugFixHandler } from "./BugFixHandler";
import { DocumentAnalysisHandler } from "./DocumentAnalysisHandler";
import { GeneralTaskHandler } from "./GeneralTaskHandler";
import { VideoGenerationHandler } from "./VideoGenerationHandler";
import { MusicGenerationHandler } from "./MusicGenerationHandler";
import { TextToSpeechHandler } from "./TextToSpeechHandler";
import { SpeechToTextHandler } from "./SpeechToTextHandler";
import { InternetSearchHandler } from "./InternetSearchHandler";
import { CodeExecutionHandler } from "./CodeExecutionHandler";

export const registerDefaultHandlers = (router: AIRouter): void => {
  const pm = router.providers;
  const { monitor, logger } = router;
  router.dispatcher.register(TaskType.TextChat, new TextChatHandler(pm, monitor, logger));
  router.dispatcher.register(TaskType.VoiceChat, new VoiceChatHandler(pm, monitor, logger));
  router.dispatcher.register(TaskType.ImageGeneration, new ImageGenerationHandler(pm, monitor, logger));
  router.dispatcher.register(TaskType.ImageAnalysis, new ImageAnalysisHandler(pm, monitor, logger));
  router.dispatcher.register(TaskType.WebsiteGeneration, new WebsiteGenerationHandler(pm, monitor, logger));
  router.dispatcher.register(TaskType.ApplicationGeneration, new ApplicationGenerationHandler(pm, monitor, logger));
  router.dispatcher.register(TaskType.CodeReview, new CodeReviewHandler(pm, monitor, logger));
  router.dispatcher.register(TaskType.BugFix, new BugFixHandler(pm, monitor, logger));
  router.dispatcher.register(TaskType.DocumentAnalysis, new DocumentAnalysisHandler(pm, monitor, logger));
  router.dispatcher.register(TaskType.GeneralAI, new GeneralTaskHandler(pm, monitor, logger));
  router.dispatcher.register(TaskType.VideoGeneration, new VideoGenerationHandler(pm, monitor, logger));
  router.dispatcher.register(TaskType.MusicGeneration, new MusicGenerationHandler(pm, monitor, logger));
  router.dispatcher.register(TaskType.TextToSpeech, new TextToSpeechHandler(pm, monitor, logger));
  router.dispatcher.register(TaskType.SpeechToText, new SpeechToTextHandler(pm, monitor, logger));
  router.dispatcher.register(TaskType.InternetSearch, new InternetSearchHandler(pm, monitor, logger));
  router.dispatcher.register(TaskType.CodeExecution, new CodeExecutionHandler(pm, monitor, logger));
};
